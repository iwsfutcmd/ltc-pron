HEADER = '''-- Tests for Module:ltc-pron/predict. Generated by scripts/make_testcases.py in
-- https://github.com/iwsfutcmd/ltc-pron; run with
-- {{#invoke:ltc-pron/predict/testcases|run_tests}}.

local tests = require("Module:UnitTests")
local m_pron = require("Module:ltc-pron")
local m_predict = require("Module:ltc-pron/predict")
local data = mw.loadData("Module:ltc-pron/data")

local function plain(jyutping)
	return jyutping and (jyutping:gsub("<sup>(%d)</sup>", "%1")) or "–"
end

-- Check the literary and colloquial Cantonese reflexes of one MC reading,
-- written as in Module:zh/data/ltc-pron. "–" means no colloquial form.
local function check(self, char, reading, literary, colloquial, note)
	local initial, final = m_pron.infer_categories(reading)
	local tone = data.tone_number[mw.ustring.sub(reading, 6, 6)]
	self:equals({ char, reading, "literary", note },
		plain(m_predict.predict_yue(initial, final, tone)), literary)
	self:equals({ char, reading, "colloquial", note },
		plain(m_predict.predict_yue_coll(initial, final, tone)), colloquial)
end
'''


def lua_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build() -> str:
    chars = load_chars()
    parts = [HEADER]
    for name, (title, cases) in GROUPS.items():
        parts.append(f"\n-- {title}\nfunction tests:test_{name}()")
        for char, selector, lit, coll, note in cases:
            readings = [r for r in chars[char].mc if selector in r]
            if not readings:
                sys.exit(f"no MC reading of {char} contains {selector!r}")
            args = ", ".join(lua_string(x) for x in (char, readings[0], lit, coll or "–", note))
            parts.append(f"\tcheck(self, {args})")
        parts.append("end")
    parts.append("\nreturn tests\n")
    return "\n".join(parts)


def run_locally(source: str) -> int:
    """Run the testcases with a minimal stand-in for Module:UnitTests."""
    rt = Scribunto()
    lua = rt.lua
    lua.execute('''
        package.preload["Module:UnitTests"] = function()
            local t = { results = {} }
            function t:equals(name, actual, expected)
                table.insert(self.results, { name = table.concat(name, " | "),
                    ok = actual == expected, actual = actual, expected = expected })
            end
            return t
        end
    ''')
    tests = lua.execute(source)
    failures = 0
    total = 0
    for key in sorted(k for k in tests if str(k).startswith("test_")):
        tests[key](tests)
    for r in tests.results.values():
        total += 1
        if not r.ok:
            failures += 1
            print(f"  FAIL {r.name}: got {r.actual}, expected {r.expected}")
    print(f"{total} cases, {failures} failures")
    return failures


if __name__ == "__main__":
    source = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(source)
    print(f"wrote {OUT.relative_to(MODULES.parent)}")
    sys.exit(1 if run_locally(source) else 0)
